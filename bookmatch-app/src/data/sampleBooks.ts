// 도서 검색 유틸리티
export function getBooksByMBTI(mbtiType: string): Book[] {
  return SAMPLE_BOOKS.filter((book) => book.mbtiMatch.includes(mbtiType as any));
}

export function getBookById(id: string): Book | undefined {
  return SAMPLE_BOOKS.find((book) => book.id === id);
}

export function getBooksByCategory(category: string): Book[] {
  return SAMPLE_BOOKS.filter((book) => book.category === category);
}

export function searchBooks(query: string): Book[] {
  const lowerQuery = query.toLowerCase();
  return SAMPLE_BOOKS.filter(
    (book) =>
      book.title.toLowerCase().includes(lowerQuery) ||
      book.author.toLowerCase().includes(lowerQuery) ||
      book.keywords.some((k) => k.toLowerCase().includes(lowerQuery))
  );
}
